"""Desktop (PlatynUI) safety, isolation and focus guards for live harness steps.

Attribution
-----------
Vendored from rf-mcp (https://github.com/manykarim/rf-mcp, release 0.36.0,
commit c1a18eb, Apache-2.0, same author as this project): the active-desktop
safety guard and isolation recipe (ADR-027, ``desktop_display_safety.py``),
focus-before-act with visibility/scope/lineage checks (ADR-026,
``platynui_focus.py``), the pre-dispatch locator/screenshot guards and the
steering-confidence verdict (``desktop_execution_signals.py``), launch-env
hardening (``desktop_launch_env.py`` plus parts of ``keyword_executor.py`` and
``plugins/builtin/platynui_plugin.py``) and the locator crib
(``desktop_guidance.py``). Each module names its source. ``tests/desktop``
replays decisions recorded from rf-mcp itself (``corpus.json``, generated by
``tests/desktop/make_corpus.py``); the runtime never imports rf-mcp.

Entry points
------------
``probe_context()`` gathers display/session facts; ``evaluate_step(keyword,
args, context)`` returns a :class:`Decision` (``allowed``, ``reason``,
``guidance``, ...). A refused step must not be dispatched. Live desktop steps
stay refused unless ``RFH_DESKTOP=1`` (:func:`desktop_enabled`); with the gate
open every rf-mcp guard still applies, unchanged.

Environment variables (rf-mcp name -> harness name)
---------------------------------------------------
=========================================  =====================================
``ROBOTMCP_PLATYNUI_ISOLATED_DISPLAY``     ``RFH_PLATYNUI_ISOLATED_DISPLAY``
``ROBOTMCP_PLATYNUI_ISOLATED_XPID``        ``RFH_PLATYNUI_ISOLATED_XPID``
``ROBOTMCP_PLATYNUI_ALLOW_ACTIVE_DESKTOP`` ``RFH_PLATYNUI_ALLOW_ACTIVE_DESKTOP``
``ROBOTMCP_PLATYNUI_SAFETY_GUARD``         ``RFH_PLATYNUI_SAFETY_GUARD``
``ROBOTMCP_PLATYNUI_REQUIRE_ISOLATED``     ``RFH_PLATYNUI_REQUIRE_ISOLATED``
``ROBOTMCP_PLATYNUI_ALLOW_UNSCOPED``       ``RFH_PLATYNUI_ALLOW_UNSCOPED``
``ROBOTMCP_PLATYNUI_ALLOW_PATH_DESCRIPTOR`` ``RFH_PLATYNUI_ALLOW_PATH_DESCRIPTOR``
``ROBOTMCP_PLATYNUI_ALLOW_CONTROL_WINDOW`` ``RFH_PLATYNUI_ALLOW_CONTROL_WINDOW``
``ROBOTMCP_PLATYNUI_NO_FOCUS``             ``RFH_PLATYNUI_NO_FOCUS``
``ROBOTMCP_PLATYNUI_HIGHLIGHT``            ``RFH_PLATYNUI_HIGHLIGHT``
``ROBOTMCP_PLATYNUI_KEEP_WAYLAND``         ``RFH_PLATYNUI_KEEP_WAYLAND``
``ROBOTMCP_PLATYNUI_STEERING_CONFIDENCE``  ``RFH_PLATYNUI_STEERING_CONFIDENCE``
``ROBOTMCP_SCREENSHOT_DIR``                ``RFH_SCREENSHOT_DIR``
(harness only)                             ``RFH_DESKTOP`` (feature gate)
=========================================  =====================================

The ``ROBOTMCP_*`` names are not read. User-facing guidance is rf-mcp's text
with these renames and "rf-mcp" -> "rf-harness".
"""

